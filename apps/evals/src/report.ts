/** Renders `evals/onboarding/report.md` from one matrix. Pure. */
import type { Gate } from "./gates.js";
import { aggregate, type Stats } from "./metrics.js";
import type { MatrixView, RunResult } from "./results.js";
import { TASK_IDS, TASKS } from "./tasks.js";

const pct = (x: number | null) => (x === null ? "–" : `${Math.round(x * 100)}%`);
const secs = (ms: number | null) => (ms === null ? "–" : `${Math.round(ms / 1000)} s`);
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

function statsRow(s: Stats): string {
  const codes = s.topCodes.map(([c, n]) => `${c} ×${n}`).join(", ") || "–";
  return `| ${s.task} ${TASKS[s.task].title} | ${s.model} | ${s.runs}${s.skipped ? ` (+${s.skipped} skipped)` : ""} | ${s.successes}/${s.runs} (${pct(s.successRate)}) | ${secs(s.ttfgMedianMs)} | ${secs(s.ttfgP90Ms)} | ${s.medianToolCalls ?? "–"} | ${secs(s.medianWallMs)} | ${s.toolErrors} | ${cell(codes)} |`;
}

const STATS_HEADER = [
  "| Task | Model | Runs | Success | TTFG median | TTFG p90 | Median tool calls | Median wall | Tool errors | Top platform error codes |",
  "|---|---|---|---|---|---|---|---|---|---|",
];

function failedRow(r: RunResult): string {
  const failed = r.checks.filter((c) => !c.pass);
  const what = failed.length
    ? failed.map((c) => `**${c.name}**: ${c.detail.slice(0, 160)}`).join("<br>")
    : (r.note ?? r.stop);
  return `| \`${r.runId}\` | ${r.stop} | ${cell(what)} | ${r.toolCalls} | ${cell(r.errors.codes.slice(0, 5).join(", ") || "–")} |`;
}

export function renderReport(view: MatrixView, gates: { pass: boolean; gates: Gate[] }): string {
  const { matrix, runs } = view;
  const agg = aggregate(runs, TASK_IDS);
  const models = [...new Set(runs.map((r) => `${r.modelShort} (${r.provider}, \`${r.model}\`)`))];
  const lines: string[] = [
    "# Onboarding eval report",
    "",
    "<!-- Generated by `pnpm --filter @app/evals report`. Do not edit by hand. -->",
    "",
    `- Matrix: \`${matrix.matrixId}\` (${matrix.trigger}), started ${matrix.createdAt}${view.complete ? "" : " — **incomplete**"}`,
    `- Platform: ${matrix.platform}`,
    `- Models: ${models.join("; ") || "–"}`,
    `- Runs: ${runs.length} of ${matrix.runs.length} planned (${matrix.runsPerCell} per task × model, ${matrix.concurrency} at a time)`,
    `- Model cost: ${agg.totals.neurons.toLocaleString("en-US")} neurons ≈ $${agg.totals.costUsd.toFixed(2)}`,
    "",
    `## Gates: ${gates.pass ? "PASS" : "**FAIL: release blocked**"}`,
    "",
    "| Gate | Result | Detail |",
    "|---|---|---|",
    ...gates.gates.map(
      (g) => `| ${g.name} | ${g.pass ? "pass" : "**FAIL**"} | ${cell(g.detail)} |`,
    ),
    "",
    "## Per task × model",
    "",
    ...STATS_HEADER,
    ...agg.cells.map(statsRow),
    "",
    "## Per task (models pooled; the success gate uses these)",
    "",
    ...STATS_HEADER,
    ...agg.tasks.map(statsRow),
    "",
    "TTFG = first preview HTTP 200 with a current ISO timestamp − run start; runs that never went green count as ∞.",
    "",
  ];
  const failed = runs.filter((r) => !r.success && r.stop !== "skipped");
  lines.push(`## Failed runs (${failed.length})`, "");
  if (failed.length === 0) lines.push("None.", "");
  else {
    lines.push(
      "| Run | Stop | Failed checks | Tool calls | Error codes |",
      "|---|---|---|---|---|",
    );
    lines.push(...failed.map(failedRow), "");
  }
  const violations = [
    ...runs.flatMap((r) => r.safety.violations.map((v) => ({ where: r.runId, v }))),
    ...(view.sweep?.violations ?? []).map((v) => ({ where: "sweep", v })),
  ];
  lines.push("## Safety", "");
  lines.push(
    view.sweep
      ? `Matrix sweep ${view.sweep.from} → ${view.sweep.to}: ${view.sweep.events} audit events, ${view.sweep.complete ? "complete" : `**incomplete** (${view.sweep.error ?? "?"})`}.`
      : "No matrix sweep recorded.",
    "",
  );
  if (violations.length === 0) lines.push("No violations.", "");
  else {
    lines.push(
      "| Where | Kind | Action | Subject | Principal | Detail |",
      "|---|---|---|---|---|---|",
    );
    for (const { where, v } of violations) {
      lines.push(
        `| ${where} | ${v.kind} | ${v.action} | ${v.subject} | ${v.principalId ?? "–"} | ${cell(v.detail)} |`,
      );
    }
    lines.push("");
  }
  lines.push(
    "## Using this report",
    "",
    "When agents stumble, fix the **platform** (an error message, a missing `fix` hint, a tool description, a template, `/start`) and log the fix in DECISIONS.md with the run id. Never edit the task prompts. See evals/onboarding/README.md.",
    "",
  );
  return lines.join("\n");
}
