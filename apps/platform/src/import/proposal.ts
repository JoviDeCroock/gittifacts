/**
 * What the platform proposes for an imported repo, from its `DetectReport`: the files
 * (`.platform/ci.ts`, `.platform/policy.ts`, `AGENTS.md`, all from @app/conventions) and the Plan
 * a human approves. Pure.
 *
 * Every doubt detection had becomes its own risk declaration ("Detection is unsure: …"), so the
 * human reads each guess instead of finding it later. Files the repo already has are respected:
 * an existing `.platform/*` file is kept (it already drives CI and policy), and an AGENTS.md
 * that the platform didn't generate gets the platform's section appended, not replaced.
 */
import {
  AGENTS_MD_PATH,
  agentsMd,
  BUILD_SCRIPTS_DOUBT,
  commandsFor,
  conventionsVersionOf,
  type DetectReport,
  defaultCiTs,
  defaultPolicyTs,
  PNPM_WORKSPACE_PATH,
  pnpmFailsOnUnapprovedBuilds,
  pnpmWorkspaceSkippingBuilds,
} from "@app/conventions";
import { CI_PATH, type PlanDraftInput, POLICY_PATH, type Repo } from "@app/domain";

export interface ExistingFiles {
  ci: boolean;
  policy: boolean;
  /** The current AGENTS.md text, or null when absent. */
  agentsMd: string | null;
  /**
   * The current pnpm-workspace.yaml text, null when absent, undefined when it wasn't read (a
   * proposal whose base step ran before this field existed): then the file is never written.
   */
  pnpmWorkspace?: string | null | undefined;
}

/** The default branch's own CI result (its bootstrap run at the proposal's base), if finished. */
export type MainCi =
  | { status: "passed" }
  | { status: "failed"; failedSteps: string[] }
  | { status: "unknown" };

export interface ProposalContent {
  /** path → content; empty when nothing needs to change. */
  files: Record<string, string>;
  plan: PlanDraftInput;
  changeTitle: string;
  commitMessage: string;
}

const MAX_RISKS = 50;

function bullet(label: string, value: string | null | undefined): string | null {
  return value === null || value === undefined || value === "" ? null : `- ${label}: ${value}`;
}

/**
 * "The proposal's CI passes" is only honest when main passes too: a step that already fails on
 * the default branch (a red test the repo was imported with) fails here as well.
 */
export function mainCiCriterion(mainCi: MainCi): string {
  if (mainCi.status === "passed") {
    return "The proposal's own CI run passes (the default branch passes the same steps today)";
  }
  if (mainCi.status === "failed" && mainCi.failedSteps.length > 0) {
    const steps = mainCi.failedSteps.map((s) => `\`${s}\``).join(", ");
    return `The proposal's CI runs the same steps as the default branch and every step that passes there passes here; ${steps} already ${mainCi.failedSteps.length === 1 ? "fails" : "fail"} on the default branch (pre-existing, not caused by this Change)`;
  }
  return "The proposal's CI runs the same steps as the default branch and every step that passes there passes here (a step that already fails on the default branch is pre-existing)";
}

export function buildProposal(input: {
  repo: Pick<Repo, "id" | "name" | "claim" | "importedFrom">;
  report: DetectReport;
  existing: ExistingFiles;
  host: string;
  /** Main's CI at the base, for an honest acceptance criterion (unknown when not finished). */
  mainCi?: MainCi;
}): ProposalContent {
  const { repo, report, existing } = input;
  const mainCi = input.mainCi ?? { status: "unknown" };
  const files: Record<string, string> = {};
  const kept: string[] = [];
  const ci = defaultCiTs(report.features, report);
  const policy = defaultPolicyTs({ worker: report.features.worker || report.workers.length > 0 });
  if (existing.ci) kept.push(CI_PATH);
  else files[CI_PATH] = ci.text;
  if (existing.policy) kept.push(POLICY_PATH);
  else files[POLICY_PATH] = policy.text;
  const generated = agentsMd({
    projectName: repo.name,
    host: input.host,
    mcpUrl: `${input.host.replace(/\/+$/, "")}/mcp`,
    repoId: repo.id,
    claimed: repo.claim.status === "claimed",
    commands: commandsFor(report.features),
  });
  let agentsNote: string | null = null;
  if (existing.agentsMd === null || conventionsVersionOf(existing.agentsMd) !== null) {
    if (existing.agentsMd !== generated) files[AGENTS_MD_PATH] = generated;
  } else {
    files[AGENTS_MD_PATH] = `${existing.agentsMd.trimEnd()}\n\n---\n\n${generated}`;
    agentsNote =
      "AGENTS.md already existed and was not generated by the platform: the platform's section is appended below the original; check the two don't contradict each other.";
  }

  // pnpm 11 fails the install on unapproved install scripts: skip them (allowBuilds: false) so CI
  // installs, never approve them. Only when the file was read (undefined: never written).
  const needing = report.buildScriptsNeedingApproval.map((d) => d.name);
  let skippedBuilds: "written" | "unreadable" | "not-needed" = "not-needed";
  if (
    report.packageManager === "pnpm" &&
    needing.length > 0 &&
    pnpmFailsOnUnapprovedBuilds(report.packageManagerSpec) &&
    existing.pnpmWorkspace !== undefined
  ) {
    const next = pnpmWorkspaceSkippingBuilds(existing.pnpmWorkspace, needing);
    if (next !== null) {
      files[PNPM_WORKSPACE_PATH] = next;
      skippedBuilds = "written";
    } else skippedBuilds = "unreadable";
  }

  // The install-scripts sentence gets its own risk below; listing it as a doubt too repeats it.
  const doubts = [...new Set([...report.uncertain, ...ci.uncertain, ...policy.uncertain])].filter(
    (d) => !d.startsWith(BUILD_SCRIPTS_DOUBT),
  );
  const risks: PlanDraftInput["riskDeclarations"] = doubts.map((d) => ({
    area: "detection",
    description: `Detection is unsure: ${d}`.slice(0, 2000),
  }));
  if (agentsNote !== null) risks.unshift({ area: "AGENTS.md", description: agentsNote });
  if (needing.length > 0) {
    const list = needing.join(", ");
    const description =
      skippedBuilds === "written"
        ? `pnpm 11 refuses to install while these dependencies' install scripts are unapproved (ERR_PNPM_IGNORED_BUILDS): ${list}. This Change lists them as false under allowBuilds in ${PNPM_WORKSPACE_PATH}, so installs skip their scripts instead of failing; it approves nothing. If a test or the build needs one of them to run (a native module, a downloaded binary), a human sets it to true.`
        : skippedBuilds === "unreadable"
          ? `CI installs will fail (ERR_PNPM_IGNORED_BUILDS) until a human decides on these dependencies' install scripts in ${PNPM_WORKSPACE_PATH} allowBuilds (true runs one, false skips it): ${list}. Its allowBuilds is written in a form this proposal does not edit. This Change approves nothing.`
          : `These dependencies have install scripts that don't run until a human approves them (pnpm-workspace.yaml allowBuilds, or onlyBuiltDependencies before pnpm 11): ${list}. This Change approves nothing.`;
    risks.unshift({ area: "install scripts", description });
  }
  if (report.confidence === "low") {
    risks.unshift({
      area: "detection",
      description:
        "Detection confidence is low: review the generated pipeline line by line before approving.",
    });
  }

  const detected = [
    bullet(
      "Package manager",
      `${report.packageManager}${report.lockfile === null ? " (no lockfile: installs are not reproducible)" : ` (lockfile ${report.lockfile})`}`,
    ),
    bullet("Install", `\`${report.installCommand}\``),
    bullet(
      "Tests",
      report.testCommand === null
        ? "none found"
        : `\`${report.testCommand}\` (${report.testRunner ?? "unknown runner"})`,
    ),
    bullet("Typecheck", report.typecheckCommand === null ? null : `\`${report.typecheckCommand}\``),
    bullet("Lint", report.lintCommand === null ? null : `\`${report.lintCommand}\``),
    bullet("Build", report.buildCommand === null ? "none" : `\`${report.buildCommand}\``),
    bullet(
      "tsconfig",
      report.tsconfig === null
        ? null
        : `${report.tsconfig.path}${report.tsconfig.strict === true ? " (strict)" : ""}`,
    ),
    bullet("Workers", report.workers.length === 0 ? null : report.workers.join(", ")),
    bullet("Workspaces", report.workspaces.length === 0 ? null : report.workspaces.join(", ")),
  ].filter((l): l is string => l !== null);
  const proposed = Object.keys(files);
  const intent = [
    `Adopt the platform's conventions for ${repo.name}${repo.importedFrom === null ? "" : ` (imported from ${repo.importedFrom})`}. Detection inspected the default branch in a sandbox (confidence: ${report.confidence}) and found:`,
    ...detected,
    "",
    `This Change proposes ${proposed.length === 0 ? "nothing" : proposed.join(", ")}.${kept.length === 0 ? "" : ` Kept as they are: ${kept.join(", ")}.`} Nothing is applied until a human approves it: changes to .platform/** are always Lane 2.`,
    "Until it merges, CI uses the same detected defaults (no .platform/ci.ts means the default pipeline), so other Changes can start right away.",
    doubts.length === 0
      ? "Detection had no doubts."
      : `Detection was unsure about ${doubts.length} thing(s); each is listed as a risk.`,
  ].join("\n");

  return {
    files,
    changeTitle: "Adopt platform config (.platform/ci.ts, .platform/policy.ts, AGENTS.md)",
    commitMessage: `chore: adopt gittifacts platform config\n\nProposed by the platform from import detection (confidence ${report.confidence}).`,
    plan: {
      repoId: repo.id,
      title: `Adopt platform config for ${repo.name}`.slice(0, 200),
      intent: intent.slice(0, 10_000),
      acceptanceCriteria: [
        `CI installs with \`${report.installCommand}\`${report.testCommand === null ? "" : ` and runs \`${report.testCommand}\``} from .platform/ci.ts`,
        ".platform/policy.ts starts in shadow mode (Lane 0 off) with the default sensitive paths",
        "AGENTS.md tells agents how to work here, with this repo's commands",
        mainCiCriterion(mainCi),
      ],
      outOfScope: [
        "Approving dependency install scripts (a human decision in pnpm-workspace.yaml)",
        "Any change to source code, tests or dependencies",
      ],
      riskDeclarations: risks.slice(0, MAX_RISKS),
      scopePaths: [
        CI_PATH,
        POLICY_PATH,
        AGENTS_MD_PATH,
        ...(files[PNPM_WORKSPACE_PATH] === undefined ? [] : [PNPM_WORKSPACE_PATH]),
      ],
      affectedRoutes: [],
    },
  };
}
