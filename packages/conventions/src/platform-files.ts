/**
 * `.platform/ci.ts` and `.platform/policy.ts` text for a project, in the style the ci-engine and
 * the policy loader evaluate: self-contained modules with no imports. Used for templates (at create
 * time) and for imports (proposed in a Plan + Change a human approves; never applied silently).
 */
import { CI_PATH, POLICY_PATH, RepoPolicy } from "@app/domain";
import {
  type Commands,
  type Confidence,
  commandsFor,
  type Detection,
  type ProjectFeatures,
} from "./project.js";
import { CONVENTIONS_VERSION } from "./version.js";

export interface GeneratedFile {
  path: string;
  text: string;
  confidence: Confidence;
  /** What the generator had to guess; surface these in the import Plan. */
  uncertain: string[];
}

const LINE_WIDTH = 100;

// ---------------------------------------------------------------- JS literal printer

type Literal =
  | string
  | number
  | boolean
  | null
  | readonly Literal[]
  | { readonly [key: string]: Literal };

const IDENT = /^[A-Za-z_$][\w$]*$/;

function inline(value: Literal): string {
  if (Array.isArray(value)) return `[${value.map((v: Literal) => inline(v)).join(", ")}]`;
  if (value !== null && typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "{}";
    return `{ ${entries.map(([k, v]) => `${key(k)}: ${inline(v)}`).join(", ")} }`;
  }
  return JSON.stringify(value);
}

function key(k: string): string {
  return IDENT.test(k) ? k : JSON.stringify(k);
}

/** Prints `value` as a JS literal, breaking arrays/objects over lines only when they don't fit. */
function literal(value: Literal, indent: number, prefixWidth: number): string {
  const flat = inline(value);
  if (indent + prefixWidth + flat.length + 1 <= LINE_WIDTH) return flat;
  const pad = " ".repeat(indent + 2);
  const close = " ".repeat(indent);
  if (Array.isArray(value)) {
    const items = value.map((v: Literal) => `${pad}${literal(v, indent + 2, 1)},`);
    return `[\n${items.join("\n")}\n${close}]`;
  }
  if (value !== null && typeof value === "object") {
    const items = Object.entries(value).map(
      ([k, v]) => `${pad}${key(k)}: ${literal(v, indent + 2, k.length + 3)},`,
    );
    return `{\n${items.join("\n")}\n${close}}`;
  }
  return flat;
}

// ---------------------------------------------------------------- .platform/ci.ts

const CI_HEADER = `// CI pipeline, generated by gittifacts conventions v${CONVENTIONS_VERSION}. Edit freely; edits to .platform/**
// are always Lane 2 and need a human's approval.
//
// Self-contained on purpose (no imports): the platform evaluates this file in a sandbox with a
// \`ci\` builder. \`await ci.runner()\` runs a step from a fresh checkout and resolves to the finished
// step; \`step.runner()\` runs a step from that step's snapshot (so it reuses the install). Steps
// started without awaiting in between run in parallel. A step is skipped, reusing its last
// result, when none of its \`cache.inputs\` files changed.
// The platform adds its evidence steps (red/green, coverage, public API, ...) after these.
// The \`bundle\` artifact of the build step is what a rollout deploys (when a deploy target is set).

type RunnerSpec = {
  name: string;
  command: string;
  cache?: { inputs: string[] };
  artifacts?: { name: string; paths: string[] }[];
};
type Step = { runner(spec: RunnerSpec): Promise<Step> };
type Ci = Step;
`;

function installInputs(features: ProjectFeatures): string[] {
  if (features.lockfile === null) return [];
  const extra = features.packageManager === "pnpm" ? ["pnpm-workspace.yaml", ".npmrc"] : [".npmrc"];
  return ["**/package.json", features.lockfile, ...extra];
}

function runnerCall(
  receiver: string,
  name: string,
  command: string,
  cache: string | null,
  bundle: readonly string[] | null = null,
): string {
  const cachePart = cache === null ? "" : `, cache: { inputs: ${cache} }`;
  const call = `${receiver}.runner({ name: ${JSON.stringify(name)}, command: ${JSON.stringify(command)}${cachePart} })`;
  if (bundle === null) return call;
  // Too long for one line: one property per line, like the formatter would print it.
  const lines = [
    `${receiver}.runner({`,
    `      name: ${JSON.stringify(name)},`,
    `      command: ${JSON.stringify(command)},`,
    ...(cache === null ? [] : [`      cache: { inputs: ${cache} },`]),
    `      artifacts: [{ name: "bundle", paths: ${inline(bundle as Literal)} }],`,
    "    })",
  ];
  return lines.join("\n");
}

/** Options for `defaultCiTs`. */
export interface CiOptions {
  /**
   * The build step uploads these paths as the `bundle` artifact, which rollouts deploy. Only for
   * projects whose build output is a modules-only Worker the platform can deploy.
   */
  bundle?: string | readonly string[];
}

/** The steps (besides install) a project's pipeline runs, in order. */
export function ciSteps(commands: Commands): { name: string; command: string }[] {
  const steps: { name: string; command: string }[] = [];
  for (const name of ["lint", "typecheck", "test", "build"] as const) {
    const command = commands[name];
    if (command !== null) steps.push({ name, command });
  }
  return steps;
}

/**
 * `.platform/ci.ts`: install, then lint/typecheck/test/build in parallel from the install
 * snapshot (the fastest DAG: every check starts as soon as dependencies are in place).
 */
export function defaultCiTs(
  features: ProjectFeatures,
  detection?: Pick<Detection, "confidence" | "uncertain">,
  options: CiOptions = {},
): GeneratedFile {
  const bundle =
    options.bundle === undefined
      ? null
      : typeof options.bundle === "string"
        ? [options.bundle]
        : [...options.bundle];
  const uncertain = [...(detection?.uncertain ?? [])];
  const confidence = detection?.confidence ?? "high";
  if (!features.hasPackageJson) {
    const text = `${CI_HEADER}
export default async (_ci: Ci) => {
  // No package.json at the repository root, so there is nothing to run yet. Add steps with
  // \`ci.runner({ name, command })\`.
};
`;
    return { path: CI_PATH, text, confidence: "low", uncertain };
  }
  const commands = commandsFor(features);
  const steps = ciSteps(commands);
  const install = installInputs(features);
  const lines: string[] = [CI_HEADER];
  if (features.cacheInputs !== null) {
    lines.push(`const INPUTS = ${literal(features.cacheInputs, 0, "const INPUTS = ".length)};`, "");
  }
  const cachePart =
    install.length === 0
      ? ""
      : `\n    cache: { inputs: ${literal(install, 4, "cache: { inputs: ".length)} },`;
  const installCall = `ci.runner({\n    name: "install",\n    command: ${JSON.stringify(commands.install)},${cachePart}\n  })`;
  lines.push("export default async (ci: Ci) => {");
  if (steps.length === 0) {
    lines.push(`  await ${installCall};`);
  } else {
    const cache = features.cacheInputs === null ? null : "INPUTS";
    lines.push(`  const install = await ${installCall};`, "");
    lines.push("  // Independent checks run in parallel, each from the install snapshot.");
    lines.push("  await Promise.all([");
    for (const step of steps) {
      const artifact = step.name === "build" ? bundle : null;
      lines.push(`    ${runnerCall("install", step.name, step.command, cache, artifact)},`);
    }
    lines.push("  ]);");
  }
  lines.push("};", "");
  return { path: CI_PATH, text: lines.join("\n"), confidence, uncertain };
}

// ---------------------------------------------------------------- .platform/policy.ts

export interface PolicyOptions {
  /** Routes screenshotted before/after on every Change's preview. */
  previewRoutes?: string[];
  /** Added to the default sensitive paths (auth, payments, migrations, .platform, wrangler config...). */
  extraSensitivePaths?: string[];
  /** A Worker/site whose preview routes weren't given (imports): noted as uncertain. */
  worker?: boolean;
}

const POLICY_HEADER = `// Repository policy, generated by gittifacts conventions v${CONVENTIONS_VERSION}.
//
// The platform reads this file from the BASE commit of every Change (never from the Change's head),
// so an edit only affects Changes that start after it merges. Editing it is always Lane 2.
// A plain object literal with no imports, so it can be evaluated in isolation.
`;

/**
 * Keys the generated file never writes. `lane0Enabled` belongs to the platform toggle (an owner's
 * `setLane0`): a file that says `lane0Enabled: false` forces Lane 0 off on every default-branch
 * commit, so writing the default here would undo the owner's toggle at the next merge.
 */
const OMITTED_POLICY_KEYS = new Set(["lane0Enabled"]);

const POLICY_COMMENTS: Record<string, string[]> = {
  shadow: [
    "Shadow mode: Lane 0 (auto-merge) starts off. The classifier still computes it and the platform",
    "records whether humans agree; the owner turns Lane 0 on in the repo settings once agreement",
    "passes these numbers. `lane0Enabled: false` here keeps it off whatever the owner sets.",
  ],
  sensitivePaths: ["Changes touching these paths are Lane 2 (full human review)."],
  thresholds: [
    "Lane 0 needs coverage/mutation at or above these on changed lines and a diff below the size limits.",
  ],
  planlessLane0: ["Categories that may reach Lane 0 without an approved Plan (none by default)."],
  previewRoutes: [
    "Routes screenshotted before/after on every Change's preview, plus the Plan's routes.",
  ],
};

/**
 * What the generated `.platform/policy.ts` exports, as a value. The platform caches it for a new
 * repo's initial commit, so the first Change does not have to evaluate the file in a sandbox.
 */
export function defaultPolicyValue(opts: PolicyOptions = {}): RepoPolicy {
  const defaults = RepoPolicy.parse({});
  return RepoPolicy.parse({
    sensitivePaths: [...defaults.sensitivePaths, ...(opts.extraSensitivePaths ?? [])],
    previewRoutes: opts.previewRoutes ?? [],
  });
}

/** `.platform/policy.ts`: the domain defaults (shadow mode on), plus preview routes. */
export function defaultPolicyTs(opts: PolicyOptions = {}): GeneratedFile {
  const policy = defaultPolicyValue(opts);
  const uncertain: string[] = [];
  if (opts.worker === true && opts.previewRoutes === undefined) {
    uncertain.push(
      "Which routes to screenshot is unknown: previewRoutes is empty, so only Plan-declared routes get screenshots.",
    );
  }
  const lines = [POLICY_HEADER, "export default {"];
  for (const [k, v] of Object.entries(policy)) {
    if (OMITTED_POLICY_KEYS.has(k)) continue;
    for (const comment of POLICY_COMMENTS[k] ?? []) lines.push(`  // ${comment}`);
    lines.push(`  ${key(k)}: ${literal(v as Literal, 2, k.length + 2)},`);
  }
  lines.push("};", "");
  return {
    path: POLICY_PATH,
    text: lines.join("\n"),
    confidence: uncertain.length === 0 ? "high" : "medium",
    uncertain,
  };
}

// ---------------------------------------------------------------- pnpm-workspace.yaml (imports)

export const PNPM_WORKSPACE_PATH = "pnpm-workspace.yaml";

/** pnpm 11 and later fail installs on unapproved install scripts; pnpm 10 only warns. */
export function pnpmFailsOnUnapprovedBuilds(packageManagerSpec: string | null): boolean {
  const m = /^pnpm@(\d+)/.exec(packageManagerSpec ?? "");
  // No pin: the runners use pnpm 11.
  return m?.[1] === undefined || Number(m[1]) >= 11;
}

const PLAIN_KEY = /^[A-Za-z0-9._-]+$/;
const SKIP_COMMENT =
  "# Skipped by the gittifacts import proposal (their install scripts don't run); set true to approve one.";

/**
 * `pnpm-workspace.yaml` with each of `names` set to `false` under `allowBuilds`: pnpm 11 then
 * installs without running their install scripts instead of failing (`ERR_PNPM_IGNORED_BUILDS`).
 * Never approves anything (`true` stays a human's decision). Verified with pnpm 11.27.0: a
 * `--config.strict-dep-builds=false` install passes but writes placeholders into this file, and
 * the next `pnpm run` re-installs and fails, so the decision has to live in the file itself.
 *
 * `current` null = no file yet. Returns null when there is nothing to add, or when `allowBuilds`
 * is written in a form this line-based edit can't extend safely (flow style).
 */
export function pnpmWorkspaceSkippingBuilds(
  current: string | null,
  names: readonly string[],
): string | null {
  const entry = (indent: string, name: string) =>
    `${indent}${PLAIN_KEY.test(name) ? name : `'${name.replaceAll("'", "''")}'`}: false`;
  const unique = [...new Set(names)].sort();
  if (unique.length === 0) return null;
  const text = current ?? "";
  const lines = text === "" ? [] : text.replace(/\r\n/g, "\n").replace(/\n$/, "").split("\n");
  const start = lines.findIndex((l) => /^allowBuilds\s*:/.test(l));
  if (start === -1) {
    const block = ["allowBuilds:", `  ${SKIP_COMMENT}`, ...unique.map((n) => entry("  ", n))];
    return `${[...lines, ...(lines.length > 0 && lines.at(-1) !== "" ? [""] : []), ...block].join("\n")}\n`;
  }
  const inline = (lines[start] ?? "").replace(/^allowBuilds\s*:/, "").trim();
  if (inline !== "" && !inline.startsWith("#")) return null;
  let last = start;
  let indent = "  ";
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i] ?? "";
    if (line.trim() === "" || /^\s+#/.test(line)) continue;
    if (/^\S/.test(line)) break;
    if (last === start) indent = /^(\s+)/.exec(line)?.[1] ?? indent;
    last = i;
  }
  const present = new Set(
    lines
      .slice(start + 1, last + 1)
      .map((l) => /^\s+(['"]?)(.+?)\1\s*:/.exec(l)?.[2])
      .filter((n): n is string => n !== undefined),
  );
  const added = unique.filter((n) => !present.has(n));
  if (added.length === 0) return null;
  const insert = [`${indent}${SKIP_COMMENT}`, ...added.map((n) => entry(indent, n))];
  return `${[...lines.slice(0, last + 1), ...insert, ...lines.slice(last + 1)].join("\n")}\n`;
}
